def entries():
    """Return stable expressions, descriptive names, and editable search tags."""
    seen = set()
    for category, block in GROUPS.items():
        for number, text in enumerate(block.strip().splitlines(), 1):
            text = text.strip()
            if text not in seen:
                seen.add(text)
                yield text, f'{category} {number:02d}', [category]
